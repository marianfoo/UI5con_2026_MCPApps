import type { CallToolResult } from '@modelcontextprotocol/sdk/types.js';
import { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { registerAppResource, registerAppTool } from '@modelcontextprotocol/ext-apps/server';
import { buildProjectCardManifests } from './card-manifests.js';
import {
  getProjectOverview,
  summarizeProjectOverview
} from './project-overview.js';
import { readBuiltAppResource } from '../../../src/mcp-host.js';

const INTEGRATION_CARDS_RESOURCE_URI = 'ui://ui5-card-project-overview/index.html';
// External UI5 resources must be declared; the host still owns and enforces the final CSP.
const INTEGRATION_CARDS_RESOURCE_META = {
  csp: {
    connectDomains: ['https://ui5.sap.com'],
    resourceDomains: ['https://ui5.sap.com']
  },
  prefersBorder: true
};

export function registerUi5CardProjectOverviewSample(server: McpServer): void {
  // This tool uses the same MCP data flow as sample 01 but selects a different prebuilt UI.
  registerAppTool(
    server,
    'show_ui5_project_cards',
    {
      title: 'Show UI5 Project Cards',
      description: [
        'Open UI Integration Cards for the same UI5 project overview used by sample 01.',
        'Use this to compare declarative card manifests with a custom UI5 Web Components layout.'
      ].join(' '),
      inputSchema: {},
      _meta: {
        ui: {
          resourceUri: INTEGRATION_CARDS_RESOURCE_URI
        }
      }
    },
    async () => buildProjectCardsResult()
  );

  registerAppResource(
    server,
    'UI Integration Cards Project Overview',
    INTEGRATION_CARDS_RESOURCE_URI,
    {
      title: 'UI Integration Cards Project Overview',
      description: 'Declarative UI Integration Cards over the same UI5 project overview as sample 01.',
      _meta: {
        ui: INTEGRATION_CARDS_RESOURCE_META
      }
    },
    async (uri) => readBuiltAppResource('02-ui5-card-project-overview', uri, {
      uiMeta: INTEGRATION_CARDS_RESOURCE_META
    })
  );
}

export function buildProjectCardsResult(): CallToolResult {
  const overview = getProjectOverview();
  // The manifests are deterministic server output, not markup generated by the model.
  const cardManifests = buildProjectCardManifests(overview);

  return {
    content: [
      {
        type: 'text',
        text: `${summarizeProjectOverview(overview)} The Integration Cards view contains ${cardManifests.length} declarative card manifest(s).`
      }
    ],
    // The app receives both the source facts and their declarative card representation.
    structuredContent: {
      overview,
      cardManifests
    },
    _meta: {
      source: {
        kind: 'fixture',
        note: 'Card manifests are generated from the same UI5 project fixture used by sample 01.'
      }
    }
  };
}
